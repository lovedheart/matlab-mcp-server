classdef shareMATLABSessionTest < matlab.mock.TestCase
    %shareMATLABSessionTest Tests for mcpserver.internal.shareMATLABSession
    %   This test class verifies that shareMATLABSession correctly
    %   manages the application data folder, writes per-session details
    %   files, and engages the connection monitor.

    % Copyright 2026 The MathWorks, Inc.

    methods (Test)
        function testShareMATLABSession_HappyPath(testCase)
            % Arrange
            import matlab.mock.actions.AssignOutputs
            import matlab.mock.actions.DoNothing

            [mockAppData, appDataBehavior] = testCase.createMock( ...
                ?mcpserver.internal.appdata.AppDataLocator, ...
                Strict=true ...
            );
            [mockFSAdaptor, FSAdaptorBehavior] = testCase.createMock( ...
                ?mcpserver.internal.fs.FSAdaptor, ...
                Strict=true ...
            );
            [mockConnector, connectorBehavior] = testCase.createMock( ...
                ?mcpserver.internal.connector.ConnectorAdaptor, ...
                Strict=true ...
            );
            [mockFSFacade, FSFacadeBehavior] = testCase.createMock( ...
                ?mcpserver.internal.facade.fs.FSFacade, ...
                Strict=true ...
            );
            [mockConnectorFacade, connectorFacadeBehavior] = testCase.createMock( ...
                ?mcpserver.internal.facade.connector.ConnectorFacade, ...
                Strict=true ...
            );
            [mockSessionIdProvider, sessionIdBehavior] = testCase.createMock( ...
                ?mcpserver.internal.connection.SessionIdProvider, ...
                Strict=true ...
            );
            [mockMonitor, monitorBehavior] = testCase.createMock( ...
                ?mcpserver.internal.connection.ConnectionMonitor, ...
                Strict=true ...
            );

            expectedAppDataFolder = fullfile("home", "user", ".MathWorks", "MATLABMCPServer");
            expectedV1Folder = fullfile(expectedAppDataFolder, "v1");
            expectedPID = feature("getpid");
            expectedSessionDetailsPath = fullfile(expectedV1Folder, sprintf("sessionDetails_%d.json", expectedPID));
            expectedLegacySessionDetailsPath = fullfile(expectedV1Folder, "sessionDetails.json");
            expectedBeaconPaths = [ ...
                string(fullfile(expectedV1Folder, sprintf("agentConnected_%d.json", expectedPID))), ...
                string(fullfile(expectedV1Folder, "agentConnected.json"))];
            expectedPort = 31415;
            expectedCert = fullfile("home", "user", ".matlab", "connector.pem");
            expectedApiKey = "test-api-key";
            expectedSessionID = "test-session-id";
            expectedSessionDetails = struct( ...
                "port", expectedPort, ...
                "certificate", expectedCert, ...
                "apiKey", expectedApiKey, ...
                "pid", expectedPID, ...
                "sessionId", expectedSessionID ...
            );
            expectedJson = jsonencode(expectedSessionDetails, PrettyPrint=true);

            when( ...
                connectorFacadeBehavior.ensureServiceOn().withExactInputs(), ...
                DoNothing ...
            );
            when( ...
                appDataBehavior.getAppDataFolder().withExactInputs(), ...
                AssignOutputs(expectedAppDataFolder) ...
            );
            when( ...
                FSAdaptorBehavior.ensureSecureFolder(expectedAppDataFolder), ...
                DoNothing ...
            );
            when( ...
                FSAdaptorBehavior.ensureSecureFolder(expectedV1Folder), ...
                DoNothing ...
            );
            when( ...
                sessionIdBehavior.getSessionId().withExactInputs(), ...
                AssignOutputs(expectedSessionID) ...
            );
            when( ...
                connectorBehavior.getConnectionDetails().withAnyInputs(), ...
                AssignOutputs(rmfield(expectedSessionDetails, "sessionId")) ...
            );
            when( ...
                FSAdaptorBehavior.ensureSecureFile(expectedSessionDetailsPath), ...
                DoNothing ...
            );
            when( ...
                FSAdaptorBehavior.ensureSecureFile(expectedLegacySessionDetailsPath), ...
                DoNothing ...
            );
            when( ...
                FSFacadeBehavior.writelines(expectedJson, expectedSessionDetailsPath), ...
                DoNothing ...
            );
            when( ...
                FSFacadeBehavior.writelines(expectedJson, expectedLegacySessionDetailsPath), ...
                DoNothing ...
            );
            when( ...
                monitorBehavior.engage(expectedSessionDetailsPath, expectedBeaconPaths, expectedSessionID), ...
                DoNothing ...
            );

            % Act
            mcpserver.internal.shareMATLABSession( ...
                AppDataLocator=mockAppData, ...
                FSAdaptor=mockFSAdaptor, ...
                FSFacade=mockFSFacade, ...
                ConnectorAdaptor=mockConnector, ...
                ConnectorFacade=mockConnectorFacade, ...
                SessionIdProvider=mockSessionIdProvider, ...
                ConnectionMonitor=mockMonitor ...
            );

            % Assert
            testCase.verifyCalled( ...
                connectorFacadeBehavior.ensureServiceOn().withExactInputs(), ...
                "ensureServiceOn should be called to start the connector" ...
            );
            testCase.verifyCalled( ...
                sessionIdBehavior.getSessionId().withExactInputs(), ...
                "getSessionId should be called to obtain the stable session ID" ...
            );
            testCase.verifyCalled( ...
                FSAdaptorBehavior.ensureSecureFile(expectedSessionDetailsPath), ...
                "ensureSecureFile should be called for the per-session sessionDetails file" ...
            );
            testCase.verifyCalled( ...
                FSAdaptorBehavior.ensureSecureFile(expectedLegacySessionDetailsPath), ...
                "ensureSecureFile should be called for the canonical sessionDetails file" ...
            );
            testCase.verifyCalled( ...
                FSFacadeBehavior.writelines(expectedJson, expectedSessionDetailsPath), ...
                "writelines should be called with JSON content for the per-session file" ...
            );
            testCase.verifyCalled( ...
                FSFacadeBehavior.writelines(expectedJson, expectedLegacySessionDetailsPath), ...
                "writelines should be called with JSON content for the canonical file" ...
            );
            testCase.verifyCalled( ...
                monitorBehavior.engage(expectedSessionDetailsPath, expectedBeaconPaths, expectedSessionID), ...
                "engage should be called on the connection monitor" ...
            );
        end

        function testSessionIdIsStableAcrossProviders(testCase)
            % Act - two independent providers must agree, because the
            % session ID is cached for the lifetime of the MATLAB session
            providerA = mcpserver.internal.connection.DefaultSessionIdProvider();
            providerB = mcpserver.internal.connection.DefaultSessionIdProvider();

            first = providerA.getSessionId();
            second = providerB.getSessionId();

            % Assert
            testCase.verifyTrue(first ~= "");
            testCase.verifyEqual(first, second);
        end
    end

end
